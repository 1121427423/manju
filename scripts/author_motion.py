# -*- coding: utf-8 -*-
"""为 23 个镜头生成「画面内部运动」设计表 shots/motion.json。

为什么需要这张表：参考片的运动量大头来自**主体局部形变**（衣袂、雾、水、能量），
而静帧 + 相机推移的局部运动几乎为 0 —— 这是"PPT 感"的量化根因。
本表把每个镜头的关键元素拆成若干"运动层"：
    band  : 只让这一横向条带动（y0..y1, x0..x1 归一化）
    drift : 该层的整体漂移速度 (px/s)，方向即运动方向
    amp   : 有机形变的幅度（噪声驱动的布料/雾/火焰呼吸感）
    speed : 噪声流动速度
再加上：
    parallax : 远/中/近三层不同跟随倍率 → 世界有纵深
    shutter  : 子帧数，动作镜取 3~4 → 真实的快门运动模糊
"""
import json

def W(y0, y1, amp, drift=(0, 0), speed=1.0, scale=1.0, x0=0.0, x1=1.0,
      feather=0.18, rate=0.9, phase=0.0):
    return dict(kind="band", y0=y0, y1=y1, x0=x0, x1=x1, amp=amp, drift=list(drift),
                speed=speed, scale=scale, feather=feather, rate=rate, phase=phase)

# 三层视差：天空/远景跟随弱，地面/近景跟随强
PARA_DEEP = [[0.00, 0.42, 0.55], [0.42, 0.78, 1.00], [0.78, 1.00, 1.45]]
PARA_NEAR = [[0.00, 0.34, 0.60], [0.34, 0.72, 1.05], [0.72, 1.00, 1.60]]

# ---------------------------------------------------------------- 设计原则
# 1) 层与层**不重叠**（只在羽化边带交叠），避免位移叠加成糊。
# 2) 位移给"环境"（天、地、雾、水、尘），人物所在的中间带只做极小位移：
#    主体不能塌 —— 观众靠角色的轮廓辨认画面，糊掉就全废。
# 3) amp（噪声形变）保持在 4~7px，只负责"活着"；真正被看见的运动来自 drift。
SKY = (0.00, 0.36)
MID = (0.36, 0.82)      # 人物整体落在这一段：位移极小，轮廓不被剪切
GND = (0.82, 1.00)      # 只有最底部的水/碎石大幅滑动


def L(rng, amp, drift, speed=1.2, scale=1.0, x0=0.0, x1=1.0, feather=0.11,
      rate=0.9, phase=0.0):
    """一个运动层：rng=(y0,y1) 为归一化纵向区间。"""
    return dict(kind="band", y0=rng[0], y1=rng[1], x0=x0, x1=x1, amp=amp,
                drift=list(drift), speed=speed, scale=scale, feather=feather,
                rate=rate, phase=phase)


# 每镜：sky 漂移 / mid 漂移 / gnd 漂移 / 额外层 / 快门数
# 位移单位 px/s（1080p 画布上的实际像素）
MOTION_SPEC = {
  1:  ((-40, -26), (0, -6), (90, -30), [], 3),      # 赤足入水：水面向后扩散，雾上浮
  2:  ((38, -34), (-10, -10), (70, -46), [], 3),    # 箓雾爬腿：雾团斜向爬升
  3:  ((-24, -12), (6, -4), (44, -26), [], 2),      # 伞下静坐：天与地缓慢错动
  4:  ((120, -26), (34, 0), (90, 26), [], 3),       # 俯拍旋涡：伞面整体旋转感
  5:  ((96, -18), (10, -4), (44, 6), [], 2),        # 乌云横移 + 光柱
  6:  ((-18, -10), (3, -3), (26, -14), [], 1),      # 半脸特写：极缓
  7:  ((22, -12), (2, -2), (18, -8), [], 1),        # 竖瞳：瞳孔区微呼吸
  8:  ((-150, -10), (-46, -6), (170, -40), [], 4),  # 踏水入场：地面向后飞掠
  9:  ((26, 8), (0, 0), (60, 10), [], 2),           # 对峙：雨幕斜落
 10:  ((-210, -24), (-58, -8), (230, -60), [], 4),  # 冲刺：地面狂退、水被劈开
 11:  ((-90, -40), (-20, -14), (110, 40), [], 3),   # 相撞：冲击向外
 12:  ((40, -18), (8, -6), (54, -24), [], 2),       # 成盾：伞骨外张
 13:  ((-170, -20), (-30, -12), (200, -50), [], 4), # 横扫：光刃带走整个下半画面
 14:  ((20, -14), (4, -6), (34, -18), [], 2),       # 绿光蔓延（脉动）
 15:  ((16, -120), (6, -46), (60, -160), [], 4),    # 跃起：整体向上拔
 16:  ((-30, -130), (-8, -34), (70, -120), [], 3),  # 冰晶爆发：霜雾向上炸开
 17:  ((-120, -90), (-24, -30), (130, 70), [], 4),  # 对撞：双向撕开
 18:  ((20, -60), (6, -18), (40, -70), [], 3),      # 白闪余波：尘烬上浮
 19:  ((14, -70), (4, -20), (48, -54), [], 3),      # 裂缝巨手：气流上卷
 20:  ((70, -40), (12, -10), (52, -30), [], 3),     # 魔神浮现：云涌
 21:  ((30, 90), (10, 34), (60, 120), [], 3),       # 巨手砸下：整体下压
 22:  ((26, -12), (3, -2), (20, -10), [], 1),       # 金瞳：静
 23:  ((14, -8), (2, -2), (12, -6), [], 1),         # 标题：几乎静止
}

MOTION = {}
for sid, (sky, mid, gnd, extra, sh) in MOTION_SPEC.items():
    warps = []
    if any(abs(v) > 3 for v in sky):
        warps.append(L(SKY, 5.0, sky, 1.3, 1.2))
    if any(abs(v) > 3 for v in mid):
        warps.append(L(MID, 4.0, mid, 1.0, 1.0, feather=0.14))
    if any(abs(v) > 3 for v in gnd):
        warps.append(L(GND, 6.0, gnd, 1.5, 1.3))
    warps += extra
    if sid not in (23,):
        MOTION[sid] = dict(shutter=sh, parallax=PARA_NEAR if sid >= 8 else PARA_DEEP,
                           warps=warps)
MOTION[23] = dict(shutter=1, parallax=[], warps=[L((0.05, 0.95), 4.0, (10, -6), 0.8, 1.0,
                                                  feather=0.3)])

if __name__ == "__main__":
    out = {str(k): v for k, v in MOTION.items()}
    with open("shots/motion.json", "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print("wrote shots/motion.json  %d shots  warps=%d" %
          (len(out), sum(len(v["warps"]) for v in out.values())))
